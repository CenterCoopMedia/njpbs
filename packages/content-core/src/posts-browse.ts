/** Editorial discovery configuration; never changes the Post taxonomy itself. */
export const POSTS_BROWSE_ICONS = ["ballot", "heart", "train", "leaf", "play", "pin"] as const;
export type PostsBrowseIcon = (typeof POSTS_BROWSE_ICONS)[number];
export interface PostsBrowseTerm { readonly filter: "category" | "tag"; readonly value: string }
export interface PostsBrowseGroup {
  readonly id: string;
  readonly label: string;
  readonly icon: PostsBrowseIcon;
  readonly terms: readonly PostsBrowseTerm[];
  /** Use the latest matching published Post's image; no new media publication. */
  readonly cover?: PostsBrowseTerm;
}
export interface PostsBrowseConfig { readonly groups: readonly PostsBrowseGroup[] }
export const postsBrowseTermKey = (term: PostsBrowseTerm): string => JSON.stringify([term.filter, term.value]);
const object = (value: unknown): value is Record<string, unknown> => typeof value === "object" && value !== null && !Array.isArray(value);
const text = (value: unknown, max: number): value is string => typeof value === "string" && value.trim() === value && value.length > 0 && new TextEncoder().encode(value).length <= max && !/[\u0000-\u001f\u007f]/.test(value);
export function validPostsBrowseTerm(value: unknown): value is PostsBrowseTerm {
  return object(value) && Object.keys(value).length === 2 && (value.filter === "category" || value.filter === "tag") &&
    text(value.value, 200) && !/^format:/i.test(value.value);
}
export function validatePostsBrowse(value: unknown): string | null {
  if (!object(value) || Object.keys(value).length !== 1 || !Array.isArray(value.groups) || value.groups.length > 8)
    return "Posts browsing needs at most eight groups.";
  const ids = new Set<string>(), terms = new Set<string>();
  let total = 0;
  for (const group of value.groups) {
    if (!object(group) || Object.keys(group).some(key => !["id", "label", "icon", "terms", "cover"].includes(key)) ||
      !text(group.id, 64) || !/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(group.id) || (ids.has(group.id) || group.id === "unassigned-subjects")) return "Each Posts browsing group needs a unique id.";
    ids.add(group.id);
    if (!text(group.label, 80) || !POSTS_BROWSE_ICONS.includes(group.icon as PostsBrowseIcon)) return "Each Posts browsing group needs a name and an available icon.";
    if (!Array.isArray(group.terms) || group.terms.length > 300) return "A Posts browsing group can contain at most 300 subjects.";
    for (const term of group.terms) {
      if (!validPostsBrowseTerm(term)) return "Choose an exact category or topic for every subject.";
      const key = postsBrowseTermKey(term);
      if (terms.has(key)) return "A subject can belong to only one Posts browsing group.";
      terms.add(key);
    }
    total += group.terms.length;
    if (group.cover !== undefined && (!validPostsBrowseTerm(group.cover) || !group.terms.some(term => postsBrowseTermKey(term as PostsBrowseTerm) === postsBrowseTermKey(group.cover as PostsBrowseTerm))))
      return "Choose a cover subject that belongs to its group.";
  }
  return total > 600 ? "Posts browsing can arrange at most 600 subjects; other subjects remain searchable." : null;
}

