import { readFileSync, writeFileSync } from "node:fs";

const read = (file) => JSON.parse(readFileSync(new URL(file, import.meta.url), "utf8"));
const { tokens, coarsePointerTokens = {} } = read("tokens.json");
const aliases = read("alias-map.json");
const banner = "/* Generated by generate-tokens.mjs. Edit tokens.json or alias-map.json. */\n";
const render = (entries, indent = "") =>
  `${indent}:root[data-cms-theme="editorial"] {\n${entries.map(([name, value]) => `${indent}  --${name}: ${value};`).join("\n")}\n${indent}}\n`;

for (const [name, value] of Object.entries(tokens)) {
  if (!/^[a-z][a-z0-9-]*$/.test(name) || typeof value !== "string" || /[{};<>]/.test(value)) {
    throw new Error(`Invalid token: ${name}`);
  }
}

for (const [name, value] of Object.entries(coarsePointerTokens)) {
  if (!(name in tokens) || typeof value !== "string" || /[{};<>]/.test(value)) {
    throw new Error(`Invalid coarse pointer token: ${name}`);
  }
}

for (const target of Object.values(aliases)) {
  if (!(target in tokens)) throw new Error(`Unknown canonical token: ${target}`);
}
writeFileSync(new URL("tokens.css", import.meta.url), banner + render(
  Object.entries(tokens).map(([name, value]) => [`cms-${name}`, value]),
) + `\n/* Hybrid devices retain touch targets even with a fine primary pointer. */\n@media (any-pointer: coarse) {\n${render(Object.entries(coarsePointerTokens).map(([name, value]) => [`cms-${name}`, value]), "  ")}}\n`);
writeFileSync(new URL("legacy-aliases.css", import.meta.url), banner + render(
  Object.entries(aliases).map(([name, target]) => [name, `var(--cms-${target})`]),
));
