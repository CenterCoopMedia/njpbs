import { installProofFonts, expect, test } from "./fixtures";

test("row menus support keyboard and touch; selection and corrections preserve the fixture", async ({ browser, baseURL }) => {
  const desktop = await browser.newPage({ viewport: { width: 1664, height: 926 } });
  await installProofFonts(desktop.context());
  await desktop.goto(`${baseURL}/transcript-specimen.html`);
  const list = desktop.getByRole("list", { name: "Transcript passages" });
  await expect(list.getByRole("listitem")).toHaveCount(50);
  await list.evaluate(element => { element.scrollTop = 1000; });
  await desktop.getByRole("button", { name: "Back to top", exact: true }).click();
  await expect.poll(() => list.evaluate(element => element.scrollTop)).toBe(0);
  await list.evaluate(element => { element.scrollTop = 1000; });
  await desktop.getByRole("button", { name: "Next page", exact: true }).click();
  await expect.poll(() => list.evaluate(element => element.scrollTop)).toBe(0);
  await expect(list.getByRole("listitem").first()).toHaveAccessibleName("Passage 51: Alex Rivera");
  await list.evaluate(element => { element.scrollTop = 1000; });
  await desktop.getByRole("searchbox", { name: "Search loaded transcript" }).fill("photograph");
  await expect.poll(() => list.evaluate(element => element.scrollTop)).toBe(0);
  await desktop.getByRole("button", { name: "Clear filters", exact: true }).click();
  const fragment = desktop.getByRole("listitem", { name: "Passage 2: Alex Rivera" });
  await expect(fragment.getByText("if", { exact: true })).toBeVisible();
  const menu = fragment.getByRole("button", { name: "Passage 2 actions" });
  await menu.focus();
  await desktop.keyboard.press("ArrowDown");
  await expect(desktop.getByRole("menuitem", { name: /Passage details/ })).toBeFocused();
  await expect(desktop.getByRole("menuitem", { name: /Passage details/ })).toContainText("00:00:00.180");
  await expect(desktop.getByRole("menuitem", { name: "Use passage 2 as clip" })).toHaveCount(0);
  await desktop.keyboard.press("Escape");
  await expect(menu).toBeFocused();
  await desktop.getByRole("button", { name: "Select passages", exact: true }).click();
  await desktop.getByRole("checkbox", { name: "Select passage 2", exact: true }).check();
  await expect(desktop.getByRole("button", { name: "Use selected range as clip" })).toBeDisabled();
  await desktop.getByRole("checkbox", { name: "Select passage 3", exact: true }).check();
  await desktop.getByRole("button", { name: "Use selected range as clip" }).click();
  await expect(desktop.getByLabel("Clip fields")).toHaveText("8.12 to 11.94");
  await desktop.getByRole("searchbox", { name: "Search loaded transcript" }).fill("photograph");
  await expect(desktop.getByRole("region", { name: "Clip selection" })).toContainText("2 outside this page or filter");
  await desktop.getByRole("button", { name: "Cancel selection" }).click();
  await desktop.getByRole("button", { name: "Clear filters" }).click();
  await desktop.getByRole("button", { name: "Edit transcript", exact: true }).click();
  await desktop.getByRole("textbox", { name: "Passage 1", exact: true }).fill("Draft one");
  await fragment.getByRole("button", { name: "Passage 2 actions" }).click();
  await desktop.getByRole("menuitem", { name: "Edit passage 2", exact: true }).click();
  await expect(desktop.getByRole("textbox", { name: /^Passage / })).toHaveCount(1);
  await desktop.getByRole("textbox", { name: "Passage 2", exact: true }).fill("Draft two");
  await desktop.getByRole("button", { name: "Passage 1 actions" }).click();
  await desktop.getByRole("menuitem", { name: "Edit passage 1", exact: true }).click();
  await expect(desktop.getByRole("textbox", { name: "Passage 1", exact: true })).toHaveValue("Draft one");
  await desktop.close();

  const phone = await browser.newPage({ viewport: { width: 320, height: 740 }, isMobile: true, hasTouch: true });
  await installProofFonts(phone.context());
  await phone.goto(`${baseURL}/transcript-specimen.html`);
  const trigger = phone.getByRole("button", { name: "Passage 1 actions" });
  await trigger.scrollIntoViewIfNeeded();
  const box = await trigger.boundingBox();
  expect(box?.width).toBeGreaterThanOrEqual(44);
  expect(box?.height).toBeGreaterThanOrEqual(44);
  await trigger.tap();
  await expect(phone.getByRole("menu")).toBeVisible();
  await expect(phone.getByRole("menuitem", { name: /Passage details/ })).toBeVisible();
  await phone.keyboard.press("Escape");
  await phone.getByRole("button", { name: "Select passages", exact: true }).tap();
  await phone.getByRole("checkbox", { name: "Select passage 1", exact: true }).tap();
  await phone.evaluate(() => { document.documentElement.style.fontSize = "200%"; });
  await phone.addStyleTag({ content: "* { transition: none !important; }" });
  const overflow = await phone.evaluate(() => {
    const list = document.querySelector<HTMLElement>(".transcript-passages")!;
    return { document: document.documentElement.scrollWidth > innerWidth, list: list.scrollWidth > list.clientWidth };
  });
  expect(overflow).toEqual({ document: false, list: false });
  // No-overflow checks alone miss a one-character-wide text column.
  const body = await phone.locator(".transcript-passage").first().boundingBox();
  const readingBox = await phone.locator(".transcript-passages").boundingBox();
  expect(body!.width).toBeGreaterThanOrEqual(readingBox!.width * 0.8);
  await expect(phone.locator(".transcript-passage-text").first()).toHaveCSS("font-size", "30px");
  const checkTarget = await phone.locator(".transcript-selection-check").first().boundingBox();
  expect(checkTarget!.width).toBeGreaterThanOrEqual(44);
  expect(checkTarget!.height).toBeGreaterThanOrEqual(44);
  await phone.close();
});

test("transcript list keeps vertical scroll chaining enabled", async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto("/transcript-specimen.html");
  const list = page.getByRole("list", { name: "Transcript passages" });
  await expect(list).toHaveCSS("overscroll-behavior-y", "auto");
  await list.scrollIntoViewIfNeeded();
  await list.evaluate(element => { element.scrollTop = element.scrollHeight - element.clientHeight; });
  const before = await page.evaluate(() => scrollY);
  await list.hover();
  await page.mouse.wheel(0, 600);
  await expect.poll(() => page.evaluate(() => scrollY)).toBeGreaterThan(before);
});

test("focused corrections and speaker naming retain the reading list and scroll position", async ({ page }) => {
  await page.setViewportSize({ width: 1664, height: 926 });
  await page.goto("/transcript-specimen.html");
  const list = page.getByRole("list", { name: "Transcript passages" });
  const originalList = await list.elementHandle();
  const actions = page.getByRole("button", { name: "Passage 40 actions", exact: true });
  await actions.click();
  const readingPosition = await list.evaluate(element => element.scrollTop);
  expect(readingPosition).toBeGreaterThan(1000);
  await page.getByRole("menuitem", { name: /^Rename / }).click();
  expect(await list.evaluate((element, previous) => element === previous, originalList)).toBe(true);
  await expect.poll(() => list.evaluate(element => element.scrollTop)).toBe(readingPosition);
  await page.getByRole("button", { name: "Cancel edits", exact: true }).click();
  expect(await list.evaluate((element, previous) => element === previous, originalList)).toBe(true);
  await expect.poll(() => list.evaluate(element => element.scrollTop)).toBe(readingPosition);
  await actions.click();
  await page.getByRole("menuitem", { name: "Edit passage 40", exact: true }).click();
  expect(await list.evaluate((element, previous) => element === previous, originalList)).toBe(true);
  await page.getByRole("textbox", { name: "Passage 40", exact: true }).fill("A focused correction deep in the loaded page.");
  await page.getByRole("button", { name: "Save transcript", exact: true }).click();
  await expect(page.getByText("Transcript corrections saved.", { exact: true })).toBeVisible();
  expect(await list.evaluate((element, previous) => element === previous, originalList)).toBe(true);
  expect(await list.evaluate(element => element.scrollTop)).toBeGreaterThan(1000);
});
