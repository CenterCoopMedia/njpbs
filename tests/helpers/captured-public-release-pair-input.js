import { readFileSync } from "node:fs";
import { createHash } from "node:crypto";
import protocol from "../../functions/lib/public-release-pair.js";
import work from "../../functions/lib/public-release-pair-work.js";

// Independently captured approved source data. Expected hashes use these bytes
// and standard SHA-256, never the input codec/capture writer's return values.
const source = JSON.parse(readFileSync(new URL("../../site/tests/fixtures/shadow-posts/post.json", import.meta.url), "utf8"));
const canonical = value => Array.isArray(value) ? `[${value.map(canonical).join(",")}]`
  : value && typeof value === "object" ? `{${Object.keys(value).sort().map(key => `${JSON.stringify(key)}:${canonical(value[key])}`).join(",")}}`
    : JSON.stringify(value);
const bytesOf = value => new TextEncoder().encode(canonical(value));
const sha = bytes => createHash("sha256").update(bytes).digest("hex");
export const capturedSnapshotBytes = bytesOf(source.document.published);
export const capturedSnapshotDigest = sha(capturedSnapshotBytes);
const contextBytes = bytesOf({ kind: source.kind, document: { id: source.document.id, status: "published",
  publiclyVisible: true, published: source.document.published }, assets: source.assets });

export function capturedPairInput(pair, overrides = {}, cursorOverride = {}) {
  const scope = { kind: "qualification", sourceOperationId: "operation-one", sourceVersion: source.document.published.sourceVersion,
    snapshotDigest: capturedSnapshotDigest, contextSequence: 12, ...overrides };
  const cursor = { baselineDigest: "b".repeat(64), sequence: scope.contextSequence, lastDigest: "c".repeat(64), ...cursorOverride };
  const files = [
    { name: "context.json", bytes: new Uint8Array(contextBytes), dependencies: [] },
    { name: "snapshot.json", bytes: new Uint8Array(capturedSnapshotBytes), dependencies: ["context.json"] },
  ];
  // The manifest layout is the independently authored capture fixture, not an
  // object generated by parsePublicReleasePairInputRoot or the new writer.
  const capturedSource = { kind: source.document.published.metadata.type, id: source.document.id };
  const root = { schemaVersion: 2, kind: "pair-render-input", pairDigest: protocol.publicReleaseDigest(pair), source: capturedSource,
    scope, cursor, snapshotFile: "snapshot.json", entryFiles: ["snapshot.json"],
    files: files.map(file => ({ name: file.name, digest: sha(file.bytes), bytes: file.bytes.byteLength,
      objectKey: `release-pair-inputs/v2/${pair.pairId}/objects/${sha(file.bytes)}.json`, dependencies: file.dependencies })) };
  const rootBytes = new TextEncoder().encode(JSON.stringify(root)), inputManifestDigest = sha(rootBytes);
  const manifestKey = `release-pair-inputs/v2/${pair.pairId}/manifests/${inputManifestDigest}.json`;
  const proof = createHash("sha256").update("private-pair-input-readback-v2\n").update(inputManifestDigest + "\n");
  for (const file of root.files) proof.update(JSON.stringify([file.name, file.digest, file.bytes, file.objectKey]) + "\n");
  const receipt = { schemaVersion: 2, status: "captured", pairDigest: root.pairDigest, source: capturedSource, scope, inputManifestDigest,
    manifestKey, manifestBytes: rootBytes.byteLength, cursor, fileCount: files.length,
    inputBytes: files.reduce((sum, file) => sum + file.bytes.byteLength, 0), readbackDigest: proof.digest("hex") };
  return { scope, cursor, files, root, rootBytes, inputManifestDigest, receipt, taskInput: { ...scope, inputManifestDigest } };
}

/** Establish a historical completed-capture fixture for work-owner tests.
 * Capture API tests independently exercise the actual R2 write/readback path. */
export async function seedCapturedPairInput(firestore, pair, overrides = {}, cursor = {}) {
  const fixture = capturedPairInput(pair, overrides, cursor);
  await firestore.doc(`${work.publicReleasePairPath(pair.pairId)}/inputs/${fixture.inputManifestDigest}`).set(fixture.receipt);
  const scopeKey = protocol.publicReleaseDigest({ schemaVersion: 2, pair: protocol.publicReleasePairReference(pair), ...fixture.scope });
  await firestore.doc(`${work.publicReleasePairPath(pair.pairId)}/inputScopes/${scopeKey}`).set({ schemaVersion: 2,
    pairDigest: protocol.publicReleaseDigest(pair), scope: fixture.scope, inputManifestDigest: fixture.inputManifestDigest,
    receiptDigest: protocol.publicReleaseDigest(fixture.receipt) });
  return fixture;
}
